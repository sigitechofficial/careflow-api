const THIN_BORDER: Partial<ExcelJS.Borders> = {
  top: { style: 'thin', color: { argb: 'FFCBD5E1' } },
  left: { style: 'thin', color: { argb: 'FFCBD5E1' } },
  bottom: { style: 'thin', color: { argb: 'FFCBD5E1' } },
  right: { style: 'thin', color: { argb: 'FFCBD5E1' } },
};

const META_FRAME = { style: 'medium' as const, color: { argb: 'FF1E293B' } };

function metaSplitColumn(totalCols: number): number {
  return Math.max(3, Math.floor(totalCols / 2));
}

/**
 * Right metadata sits over day columns (5.5 wide). Merge enough columns for labels
 * so total width is comparable to column A (~34) without widening any single day col.
 */
const RIGHT_META_LABEL_COL_COUNT = 7;

function rightMetaColumns(
  splitCol: number,
  totalCols: number,
): { labelStart: number; labelEnd: number; valueStart: number; valueEnd: number } {
  const labelStart = splitCol + 1;
  const valueEnd = totalCols;
  const halfLen = valueEnd - labelStart + 1;
  const labelCount = Math.min(
    RIGHT_META_LABEL_COL_COUNT,
    Math.max(2, halfLen - 1),
  );
  const labelEnd = labelStart + labelCount - 1;
  return {
    labelStart,
    labelEnd,
    valueStart: labelEnd + 1,
    valueEnd,
  };
}

/** Wide enough columns for the metadata / legend block (before day columns are narrowed). */
function ensureHeaderColumnWidths(ws: ExcelJS.Worksheet, totalCols: number): void {
  const splitCol = metaSplitColumn(totalCols);
  ws.getColumn(1).width = 20;
  ws.getColumn(2).width = 28;
  for (let c = 3; c <= splitCol; c++) {
    ws.getColumn(c).width = 10;
  }
  for (let c = splitCol + 1; c <= totalCols; c++) {
    ws.getColumn(c).width = 10;
  }
}

function setMarGridColumnWidths(ws: ExcelJS.Worksheet, dayCount: number): void {
  ws.getColumn(1).width = 38;
  ws.getColumn(2).width = 14;
  for (let i = 0; i < dayCount; i++) {
    ws.getColumn(3 + i).width = 5.5;
  }
}

function hexToArgb(hex: string | null | undefined): string | undefined {
  if (!hex?.trim()) return undefined;
  const raw = hex.trim().replace('#', '');
  if (/^[0-9A-Fa-f]{6}$/.test(raw)) return `FF${raw.toUpperCase()}`;
  if (/^[0-9A-Fa-f]{3}$/.test(raw)) {
    return `FF${raw[0]}${raw[0]}${raw[1]}${raw[1]}${raw[2]}${raw[2]}`.toUpperCase();
  }
  return undefined;
}

function metaItems(ctx: MarExportContext): Array<[string, string]> {
  return [
    ['Organisation', ctx.organisationName ?? '—'],
    ['Reporting month', ctx.reportMonthLabel],
    ['Period', `${ctx.periodStart} to ${ctx.periodEnd}`],
    ['Service user', ctx.serviceUserLabel],
    ['Date of birth', ctx.dateOfBirth ?? '—'],
    ['NHS number', ctx.nhsNumber ?? '—'],
    ['Location', ctx.locationName ?? '—'],
    ['Allergies', ctx.allergySummary ?? 'None recorded'],
    ['Medications', String(ctx.medicationCount)],
    ['Administration rows', String(ctx.administrationRowCount)],
    ...marCompletionMetaRows(ctx.monthStats),
    ['Generated at', ctx.generatedAt],
    ['Generated by', ctx.generatedBy ?? '—'],
  ];
}

function applyMetaFrame(
  ws: ExcelJS.Worksheet,
  topRow: number,
  bottomRow: number,
  totalCols: number,
): void {
  for (let r = topRow; r <= bottomRow; r++) {
    for (let c = 1; c <= totalCols; c++) {
      const cell = ws.getCell(r, c);
      const border: Partial<ExcelJS.Borders> = { ...THIN_BORDER };
      if (r === topRow) border.top = META_FRAME;
      if (r === bottomRow) border.bottom = META_FRAME;
      if (c === 1) border.left = META_FRAME;
      if (c === totalCols) border.right = META_FRAME;
      cell.border = border;
      if (!cell.fill) {
        cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFFFFFFF' } };
      }
    }
  }
}

function writeMetaPair(
  ws: ExcelJS.Worksheet,
  row: number,
  labelStart: number,
  labelEnd: number,
  valueStart: number,
  valueEnd: number,
  label: string,
  value: string,
): void {
  if (labelEnd > labelStart) {
    ws.mergeCells(row, labelStart, row, labelEnd);
  }
  const labelCell = ws.getCell(row, labelStart);
  labelCell.value = `${label}:`;
  labelCell.font = { size: 9, color: { argb: 'FF64748B' } };
  labelCell.alignment = { vertical: 'middle', horizontal: 'left' };

  if (valueEnd >= valueStart) {
    ws.mergeCells(row, valueStart, row, valueEnd);
  }
  const valueCell = ws.getCell(row, valueStart);
  valueCell.value = value;
  valueCell.font = { size: 9, bold: true, color: { argb: 'FF0F172A' } };
  valueCell.alignment = { vertical: 'middle', horizontal: 'left', wrapText: true };
}

function writeMetaGrid(
  ws: ExcelJS.Worksheet,
  startRow: number,
  totalCols: number,
  ctx: MarExportContext,
): number {
  const items = metaItems(ctx);
  const splitCol = metaSplitColumn(totalCols);
  const rightCols = rightMetaColumns(splitCol, totalCols);

  let row = startRow;
  for (let i = 0; i < items.length; i += 2) {
    const [leftLabel, leftValue] = items[i]!;
    writeMetaPair(ws, row, 1, 1, 2, splitCol, leftLabel, leftValue);

    if (i + 1 < items.length) {
      const [rightLabel, rightValue] = items[i + 1]!;
      writeMetaPair(
        ws,
        row,
        rightCols.labelStart,
        rightCols.labelEnd,
        rightCols.valueStart,
        rightCols.valueEnd,
        rightLabel,
        rightValue,
      );
    }

    ws.getRow(row).height = 20;
    row += 1;
  }

  applyMetaFrame(ws, startRow, row - 1, totalCols);
  return row;
}

/** Legend chips use day columns only — col A/B are much wider and skew the first items. */
const LEGEND_START_COL = 3;
const LEGEND_ITEMS_PER_ROW = 5;

function legendColumnSpans(itemCount: number, availableCols: number): number[] {
  const count = Math.max(1, itemCount);
  const base = Math.floor(availableCols / count);
  const remainder = availableCols % count;
  return Array.from({ length: count }, (_, i) => base + (i < remainder ? 1 : 0));
}

function writeLegend(
  ws: ExcelJS.Worksheet,
  startRow: number,
  totalCols: number,
  legend: MarExportChartPayload['legend'],
): number {
  ws.mergeCells(startRow, 1, startRow, totalCols);
  const titleCell = ws.getCell(startRow, 1);
  titleCell.value = 'STATUS LEGEND';
  titleCell.font = {
    bold: true,
    size: 9,
    color: { argb: 'FF475569' },
  };
  titleCell.alignment = { vertical: 'middle', horizontal: 'left' };
  let row = startRow + 1;

  const availableCols = Math.max(1, totalCols - LEGEND_START_COL + 1);

  for (let i = 0; i < legend.length; i += LEGEND_ITEMS_PER_ROW) {
    const rowItems = legend.slice(i, i + LEGEND_ITEMS_PER_ROW);
    const spans = legendColumnSpans(rowItems.length, availableCols);
    let col = LEGEND_START_COL;

    for (let j = 0; j < rowItems.length; j++) {
      const item = rowItems[j]!;
      const span = spans[j]!;
      const endCol = col + span - 1;
      ws.mergeCells(row, col, row, endCol);
      const cell = ws.getCell(row, col);
      cell.value = `${item.code} = ${item.label}`;
      cell.font = {
        size: 9,
        bold: true,
        color: { argb: hexToArgb(item.textColor) ?? 'FFFFFFFF' },
      };
      const bg = hexToArgb(item.color);
      if (bg) {
        cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: bg } };
      }
      cell.alignment = { horizontal: 'center', vertical: 'middle', wrapText: true };
      cell.border = THIN_BORDER;
      col = endCol + 1;
    }

    ws.getRow(row).height = 22;
    row += 1;
  }

  return row + 1;
}

function formatPackMemberDetailText(row: MarExportMedicationRow): string {
  return medicationDetailFields(row)
    .filter(f => f.label !== 'Pack')
    .map(f => `${f.label}: ${f.value}`)
    .join('\n');
}

function applyCompartmentAggregateCellStyle(
  cell: ExcelJS.Cell,
  aggregate: CompartmentExportAggregateCell,
): void {
  cell.value = compartmentSummaryExportCode(aggregate);
  cell.alignment = { horizontal: 'center', vertical: 'middle', wrapText: false };
  cell.font = { size: 9, bold: true };
  cell.border = THIN_BORDER;

  if (aggregate.kind === 'partial') {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFFFEDD5' } };
    cell.font = { ...cell.font, color: { argb: 'FFC2410C' }, bold: true };
    if (aggregate.tooltip) cell.note = aggregate.tooltip;
    return;
  }
  if (aggregate.kind === 'due') {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFFEF9C3' } };
    cell.font = { ...cell.font, color: { argb: 'FF854D0E' }, bold: true };
    return;
  }
  if (aggregate.kind === 'na') {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF8FAFC' } };
    cell.font = { ...cell.font, color: { argb: 'FF94A3B8' }, bold: false };
    return;
  }
  if (aggregate.kind === 'uniform') {
    applyCellStyle(cell, aggregate.cell);
    return;
  }
  cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF8FAFC' } };
}

function stylePackHeaderRow(ws: ExcelJS.Worksheet, row: number, totalCols: number, label: string): void {
  ws.mergeCells(row, 1, row, totalCols);
  const cell = ws.getCell(row, 1);
  cell.value = label;
  cell.font = { bold: true, size: 10, color: { argb: 'FF6D28D9' } };
  cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF5F3FF' } };
  cell.alignment = { horizontal: 'left', vertical: 'middle', wrapText: true };
  cell.border = {
    top: { style: 'medium', color: { argb: 'FFE9D5FF' } },
    left: { style: 'medium', color: { argb: 'FF8B5CF6' } },
    bottom: { style: 'thin', color: { argb: 'FFE9D5FF' } },
    right: { style: 'thin', color: { argb: 'FFE9D5FF' } },
  };
  ws.getRow(row).height = 22;
}

function writeCompartmentSummaryRow(
  ws: ExcelJS.Worksheet,
  row: number,
  days: number[],
  compartment: MarExportCompartmentSlice,
  todayDay: number | null,
): number {
  const medCell = ws.getCell(row, 1);
  medCell.value = `${compartment.label}\n${compartmentMedicineContentsLine(compartment.rows)}`;
  medCell.alignment = { vertical: 'top', wrapText: true };
  medCell.font = { size: 9, bold: true, color: { argb: 'FF6D28D9' } };
  medCell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFFAF5FF' } };
  medCell.border = {
    top: { style: 'thin', color: { argb: 'FFE9D5FF' } },
    left: { style: 'medium', color: { argb: 'FF8B5CF6' } },
    bottom: { style: 'thin', color: { argb: 'FFE9D5FF' } },
    right: { style: 'thin', color: { argb: 'FFE9D5FF' } },
  };

  const roundLabel = `${compartment.emoji ? `${compartment.emoji} ` : ''}${compartment.roundName}`;
  const slotCell = ws.getCell(row, 2);
  slotCell.value = `${roundLabel}\n${compartment.dueTime}`;
  slotCell.alignment = { horizontal: 'center', vertical: 'top', wrapText: true };
  slotCell.font = { size: 9, bold: true, color: { argb: 'FF6D28D9' } };
  slotCell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF5F3FF' } };
  slotCell.border = THIN_BORDER;

  days.forEach((d, i) => {
    const excelCell = ws.getCell(row, 3 + i);
    applyCompartmentAggregateCellStyle(
      excelCell,
      aggregateCompartmentExportCell(compartment.rows, d, todayDay),
    );
  });

  ws.getRow(row).height = 36;
  return row + 1;
}

function writePackMemberRow(
  ws: ExcelJS.Worksheet,
  row: number,
  days: number[],
  slotRow: MarExportMedicationRow,
): number {
  const medCell = ws.getCell(row, 1);
  medCell.value = formatPackMemberDetailText(slotRow);
  medCell.alignment = { vertical: 'top', wrapText: true };
  medCell.font = { size: 9 };
  medCell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFFEFEFE' } };
  medCell.border = {
    top: THIN_BORDER.top,
    left: { style: 'medium', color: { argb: 'FFDDD6FE' } },
    bottom: THIN_BORDER.bottom,
    right: THIN_BORDER.right,
  };

  const window =
    slotRow.roundWindowStart && slotRow.roundWindowEnd
      ? `${slotRow.roundWindowStart}–${slotRow.roundWindowEnd}`
      : '';
  const slotText = slotRow.dueTime
    ? `${slotRow.timeSlot}\n${slotRow.dueTime}${window ? ` · ${window}` : ''}`
    : slotRow.timeSlot;

  const slotCell = ws.getCell(row, 2);
  slotCell.value = slotText;
  slotCell.alignment = { horizontal: 'center', vertical: 'top', wrapText: true };
  slotCell.font = { size: 9, bold: true };
  slotCell.border = THIN_BORDER;

  days.forEach((d, i) => {
    const marCell = slotRow.days.find(c => c.day === d);
    const excelCell = ws.getCell(row, 3 + i);
    if (!marCell) {
      excelCell.border = THIN_BORDER;
      excelCell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF8FAFC' } };
      return;
    }
    applyCellStyle(excelCell, marCell);
  });

  return row + 1;
}

function writeStandaloneMedicationGroups(
  ws: ExcelJS.Worksheet,
  startRow: number,
  days: number[],
  groups: MarExportMedicationRow[][],
): number {
  let row = startRow;

  for (const slots of groups) {
    const head = slots[0]!;
    const groupStartRow = row;

    slots.forEach((slotRow, slotIndex) => {
      if (slotIndex === 0) {
        const medCell = ws.getCell(row, 1);
        medCell.value = formatMedicationDetailText(head);
        medCell.alignment = { vertical: 'top', wrapText: true };
        medCell.font = { size: 9 };
        medCell.border = THIN_BORDER;
      }

      const window =
        slotRow.roundWindowStart && slotRow.roundWindowEnd
          ? `${slotRow.roundWindowStart}–${slotRow.roundWindowEnd}`
          : '';
      const slotText = slotRow.dueTime
        ? `${slotRow.timeSlot}\n${slotRow.dueTime}${window ? ` · ${window}` : ''}`
        : slotRow.timeSlot;

      const slotCell = ws.getCell(row, 2);
      slotCell.value = slotText;
      slotCell.alignment = { horizontal: 'center', vertical: 'top', wrapText: true };
      slotCell.font = { size: 9, bold: true };
      slotCell.border = THIN_BORDER;

      days.forEach((d, i) => {
        const marCell = slotRow.days.find(c => c.day === d);
        const excelCell = ws.getCell(row, 3 + i);
        if (!marCell) {
          excelCell.border = THIN_BORDER;
          excelCell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF8FAFC' } };
          return;
        }
        applyCellStyle(excelCell, marCell);
      });

      row += 1;
    });

    if (slots.length > 1) {
      ws.mergeCells(groupStartRow, 1, row - 1, 1);
      const mergedMed = ws.getCell(groupStartRow, 1);
      mergedMed.alignment = { vertical: 'top', wrapText: true };
    }

    row += 1;
  }

  return row;
}

function applyCellStyle(cell: ExcelJS.Cell, marCell: MarChartCell): void {
  cell.value = cellExportCode(marCell);
  cell.alignment = { horizontal: 'center', vertical: 'middle', wrapText: false };
  cell.font = { size: 9, bold: true };
  cell.border = THIN_BORDER;

  if (marCell.cellState === 'recorded' && marCell.color) {
    const bg = hexToArgb(marCell.color);
    const fg = hexToArgb(marCell.textColor ?? '#FFFFFF');
    if (bg) {
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: bg } };
    }
    if (fg) cell.font = { ...cell.font, color: { argb: fg }, bold: true };
    return;
  }
  if (marCell.cellState === 'due') {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFFEF9C3' } };
    cell.font = { ...cell.font, color: { argb: 'FF854D0E' }, bold: true };
    return;
  }
  if (marCell.cellState === 'na') {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF8FAFC' } };
    cell.font = { ...cell.font, color: { argb: 'FF94A3B8' }, bold: false };
    return;
  }
  if (marCell.cellState === 'prn') {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFEFF6FF' } };
    cell.font = { ...cell.font, color: { argb: 'FF1D4ED8' }, bold: true };
  }
}

function styleHeaderCell(cell: ExcelJS.Cell, value: string | number): void {
  cell.value = value;
  cell.font = { bold: true, size: 9, color: { argb: 'FF0F172A' } };
  cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF1F5F9' } };
  cell.alignment = { horizontal: 'center', vertical: 'middle', wrapText: true };
  cell.border = THIN_BORDER;
}

function mergeRowTitle(
  ws: ExcelJS.Worksheet,
  row: number,
  colEnd: number,
  value: string,
  fontSize: number,
  bold = true,
): void {
  ws.mergeCells(row, 1, row, colEnd);
  const cell = ws.getCell(row, 1);
  cell.value = value;
  cell.font = { bold, size: fontSize, color: { argb: 'FF0F172A' } };
  cell.alignment = { horizontal: 'center', vertical: 'middle' };
}

function resolveDayColumns(
  chart: MarExportChartPayload,
): Array<{ columnDay: number; date: string }> {
  if (chart.dayDates?.length) {
    return chart.dayDates.map((date, i) => ({ columnDay: i + 1, date }));
  }
  const fromRow = chart.medications[0]?.days;
  if (fromRow?.length) {
    return fromRow.map(c => ({ columnDay: c.day, date: c.date }));
  }
  return Array.from({ length: chart.lastDay }, (_, i) => ({
    columnDay: i + 1,
    date: isoDateForDay(chart.month, i + 1),
  }));
}

function sanitiseSheetName(name: string): string {
  return name.replace(/[\\/*?:\[\]]/g, ' ').trim().slice(0, 31) || 'MAR';
}

function addMarWorksheet(
  workbook: ExcelJS.Workbook,
  ctx: MarExportContext,
  chart: MarExportChartPayload,
  sheetName: string,
  options?: MarExportRenderOptions,
): void {
  const dayColumns = resolveDayColumns(chart);
  const days = dayColumns.map(d => d.columnDay);
  const totalCols = 2 + days.length;

  const ws = workbook.addWorksheet(sanitiseSheetName(sheetName), {
    properties: { defaultRowHeight: 16 },
  });

  ensureHeaderColumnWidths(ws, totalCols);

  let row = 1;

  if (ctx.organisationName) {
    mergeRowTitle(ws, row, totalCols, ctx.organisationName, 11, true);
    row += 1;
  }

  mergeRowTitle(ws, row, totalCols, 'MEDICATION ADMINISTRATION RECORD', 14, true);
  row += 1;
  mergeRowTitle(ws, row, totalCols, ctx.reportMonthLabel, 11, false);
  row += 2;

  row = writeMetaGrid(ws, row, totalCols, ctx);
  row += 1;

  if (chart.legend.length > 0) {
    row = writeLegend(ws, row, totalCols, exportLegendItems(chart));
  }

  setMarGridColumnWidths(ws, days.length);

  styleHeaderCell(ws.getCell(row, 1), 'Medication');
  styleHeaderCell(ws.getCell(row, 2), 'Time slot');
  dayColumns.forEach((col, i) => {
    styleHeaderCell(
      ws.getCell(row, 3 + i),
      marDayColumnHeader(col.date, col.columnDay),
    );
  });
  row += 1;

  const sections = buildMarExportSections(chart.medications);
  const todayDay = exportChartTodayDay(chart.month);
  let firstSection = true;

  for (const section of sections) {
    if (!firstSection) row += 1;
    firstSection = false;

    if (section.kind === 'pack') {
      stylePackHeaderRow(ws, row, totalCols, packExportHeaderLabel(section.packName, section.rows));
      row += 1;

      for (const compartment of section.compartments) {
        row = writeCompartmentSummaryRow(ws, row, days, compartment, todayDay);
        if (includePackMedicineRows(options)) {
          for (const memberRow of compartment.rows) {
            row = writePackMemberRow(ws, row, days, memberRow);
          }
        }
      }
      continue;
    }

    row = writeStandaloneMedicationGroups(ws, row, days, section.groups);
  }
}

export async function buildMarExportExcel(
  ctx: MarExportContext,
  chart: MarExportChartPayload,
  options?: MarExportRenderOptions,
): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'CareFlow';
  workbook.created = new Date();
  addMarWorksheet(workbook, ctx, chart, 'MAR', options);
  return Buffer.from(await workbook.xlsx.writeBuffer());
}

export async function buildMarExportExcelWorkbook(
  sheets: Array<{ ctx: MarExportContext; chart: MarExportChartPayload }>,
  options?: MarExportRenderOptions,
): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'CareFlow';
  workbook.created = new Date();
  for (const { ctx, chart } of sheets) {
    const label = chart.periodLabel ?? formatReportMonthLabel(chart.month);
    addMarWorksheet(workbook, ctx, chart, label, options);
  }
  return Buffer.from(await workbook.xlsx.writeBuffer());
}
