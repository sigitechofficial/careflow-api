const DOW_LETTERS = ['S', 'M', 'T', 'W', 'T', 'F', 'S'] as const;

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function dayOfWeekLetter(month: string, day: number): string {
  const [yStr, mStr] = month.split('-');
  const y = Number(yStr);
  const m = Number(mStr);
  if (!y || !m) return '';
  return DOW_LETTERS[new Date(y, m - 1, day).getDay()] ?? '';
}

function cellLabel(cell: MarChartCell): string {
  return cellExportCode(cell);
}

function cellStyle(cell: MarChartCell): string {
  if (cell.cellState === 'recorded' && cell.color) {
    return ` style="background:${cell.color};color:${cell.textColor ?? '#fff'};font-weight:700"`;
  }
  if (cell.cellState === 'due') {
    return ' style="background:#fef9c3;color:#854d0e;font-weight:700"';
  }
  if (cell.cellState === 'na') {
    return ' style="background:#f8fafc;color:#94a3b8"';
  }
  if (cell.cellState === 'prn') {
    return ' style="background:#eff6ff;color:#1d4ed8;font-weight:700"';
  }
  return '';
}

function aggregateCellStyle(aggregate: CompartmentExportAggregateCell): string {
  if (aggregate.kind === 'partial') {
    const review = aggregate.needsReview ? ' outline:2px solid #f97316;' : '';
    return ` style="background:#ffedd5;color:#c2410c;font-weight:800;${review}"`;
  }
  if (aggregate.kind === 'due') {
    return ' style="background:#fef9c3;color:#854d0e;font-weight:700"';
  }
  if (aggregate.kind === 'na') {
    return ' style="background:#f8fafc;color:#94a3b8"';
  }
  if (aggregate.kind === 'uniform') {
    return cellStyle(aggregate.cell);
  }
  return '';
}

function compartmentDayCellHtml(
  aggregate: CompartmentExportAggregateCell,
  day: number,
  chartTodayDay: number | null,
): string {
  const label = escapeHtml(compartmentSummaryExportCode(aggregate));
  const title =
    aggregate.kind === 'partial'
      ? ` title="${escapeHtml(aggregate.tooltip).replace(/\n/g, '&#10;')}"`
      : '';
  const todayClass = chartTodayDay === day ? ' col-today' : '';
  return `<td class="status-cell day-cell comp-day-summary-cell${todayClass}"${aggregateCellStyle(aggregate)}${title}>${label}</td>`;
}

function dayCellHtml(cell: MarChartCell, label: string): string {
  return `<td class="status-cell day-cell"${cellStyle(cell)}>${escapeHtml(label)}</td>`;
}

function buildMedicationDetailHtml(row: MarExportChartPayload['medications'][0]): string {
  return medicationDetailFields(row)
    .map(
      ({ label, value }) =>
        `<div><span class="med-detail-label">${escapeHtml(label)}:</span> <span class="med-detail-value">${escapeHtml(value)}</span></div>`,
    )
    .join('');
}

/** Pack member rows sit under a pack header — omit redundant Pack line. */
function buildPackMemberDetailHtml(row: MarExportChartPayload['medications'][0]): string {
  return medicationDetailFields(row)
    .filter(({ label }) => label !== 'Pack')
    .map(
      ({ label, value }) =>
        `<div><span class="med-detail-label">${escapeHtml(label)}:</span> <span class="med-detail-value">${escapeHtml(value)}</span></div>`,
    )
    .join('');
}

function buildMetaGrid(ctx: MarExportContext): string {
  const items: Array<[string, string]> = [
    ['Organisation', ctx.organisationName ?? '—'],
    ['Reporting month', ctx.reportMonthLabel],
    ['Period', `${ctx.periodStart} to ${ctx.periodEnd}`],
    ['Service user', ctx.serviceUserLabel],
    ['Date of birth', ctx.dateOfBirth ?? '—'],
    ['NHS number', ctx.nhsNumber ?? '—'],
    ['Location', ctx.locationName ?? '—'],
    ['Allergies', ctx.allergySummary ?? 'None recorded'],
    ['Medications', String(ctx.medicationCount)],
    ['Administration rows', String(ctx.administrationRowCount)],
    ...marCompletionMetaRows(ctx.monthStats),
    ['Generated at', ctx.generatedAt],
    ['Generated by', ctx.generatedBy ?? '—'],
  ];
  return items
    .map(
      ([label, value]) =>
        `<div><span class="meta-label">${escapeHtml(label)}:</span> <strong>${escapeHtml(value)}</strong></div>`,
    )
    .join('');
}

function buildColgroup(dayCount: number, forExcel: boolean): string {
  const medW = forExcel ? 180 : 168;
  const slotW = forExcel ? 80 : 72;
  const dayW = forExcel ? 32 : 28;
  const dayCols = Array.from({ length: dayCount }, () => `<col style="width:${dayW}px" />`).join('');
  return `<colgroup><col style="width:${medW}px" /><col style="width:${slotW}px" />${dayCols}</colgroup>`;
}

export function buildMarExportHtml(
  ctx: MarExportContext,
  chart: MarExportChartPayload,
  options?: MarExportRenderOptions,
): string {
  const days = Array.from({ length: chart.lastDay }, (_, i) => i + 1);
  const includeLegend = options?.includeLegend !== false;
  const forExcel = options?.forExcel === true;

  const legendHtml = includeLegend
    ? `<div class="legend-block"><div class="legend-title">Status legend</div><div class="legend">${exportLegendItems(chart)
        .map(l => {
          const dashed = l.code === 'PR' ? 'border:1px dashed #fdba74;' : '';
          return `<span class="legend-item" style="background:${l.color};color:${l.textColor};${dashed}">${escapeHtml(l.code)} = ${escapeHtml(l.label)}</span>`;
        })
        .join('')}</div></div>`
    : '';

  const headerCells = days
    .map(
      d =>
        `<th class="day-col"><div>${d}</div><div class="dow">${escapeHtml(dayOfWeekLetter(chart.month, d))}</div></th>`,
    )
    .join('');

  const sections = buildMarExportSections(chart.medications);
  const todayDay = exportChartTodayDay(chart.month);
  const bodyRows: string[] = [];
  let firstSection = true;

  for (const section of sections) {
    if (!firstSection) {
      bodyRows.push(`<tr class="gap"><td colspan="${2 + days.length}"></td></tr>`);
    }
    firstSection = false;

    if (section.kind === 'pack') {
      bodyRows.push(
        `<tr class="pack-header-row"><td colspan="${2 + days.length}">${escapeHtml(packExportHeaderLabel(section.packName, section.rows))}</td></tr>`,
      );
      for (const compartment of section.compartments) {
        appendCompartmentCollapsedRow(bodyRows, compartment, days, todayDay);
        if (includePackMedicineRows(options)) {
          for (const row of compartment.rows) {
            appendPackMemberMedicationRow(bodyRows, row, days);
          }
        }
      }
      continue;
    }

    appendMedicationGroupRows(bodyRows, section.groups, days, true);
  }

  function appendCompartmentCollapsedRow(
    rows: string[],
    compartment: MarExportCompartmentSlice,
    dayList: number[],
    chartTodayDay: number | null,
  ) {
    const metaText = compartmentMedicineContentsLine(compartment.rows);
    const pill =
      chartTodayDay != null
        ? compartmentExportStatusPill(
            summarizeCompartmentExportDay(compartment.rows, chartTodayDay),
          )
        : null;
    const pillHtml =
      pill && showCompartmentExportStatusPill(pill)
        ? `<span class="bp-comp-status-pill ${pill.tone}">${escapeHtml(pill.icon)} ${escapeHtml(pill.label)}</span>`
        : '';
    const roundLabel = `${compartment.emoji ? `${compartment.emoji} ` : ''}${compartment.roundName}`;
    const bandHtml = `<div class="bp-comp-summary-band"><div class="med-label-cell bp-comp-summary-label"><div class="bp-comp-summary-text"><div class="med-label-head"><div class="med-name">${escapeHtml(compartment.label)}</div>${pillHtml}</div><div class="med-meta">${escapeHtml(metaText)}</div></div></div><div class="bp-comp-summary-time-side"><div class="time-slot-label">${escapeHtml(roundLabel)}</div><div class="time-slot-time">${escapeHtml(compartment.dueTime)}</div></div></div>`;
    const dayCells = dayList
      .map(d =>
        compartmentDayCellHtml(
          aggregateCompartmentExportCell(compartment.rows, d, chartTodayDay),
          d,
          chartTodayDay,
        ),
      )
      .join('');
    rows.push(
      `<tr class="bp-compartment-summary-row is-visible is-collapsed"><td class="bp-comp-summary-sticky-band" colspan="2">${bandHtml}</td>${dayCells}</tr>`,
    );
  }

  function appendPackMemberMedicationRow(
    rows: string[],
    row: MarExportChartPayload['medications'][0],
    dayList: number[],
  ) {
    const medDetailHtml = buildPackMemberDetailHtml(row);
    const window =
      row.roundWindowStart && row.roundWindowEnd
        ? `${row.roundWindowStart}–${row.roundWindowEnd}`
        : '';
    const slotLabel = row.dueTime
      ? `${escapeHtml(row.timeSlot)}<div class="slot-time">${escapeHtml(row.dueTime)}${window ? ` · ${escapeHtml(window)}` : ''}</div>`
      : escapeHtml(row.timeSlot);
    const cells = dayList
      .map(d => {
        const cell = row.days.find(c => c.day === d);
        if (!cell) return '<td class="status-cell day-cell na"></td>';
        const label = cellLabel(cell);
        return dayCellHtml(cell, label);
      })
      .join('');
    rows.push(
      `<tr class="pack-member-row"><td class="med"><div class="med-details">${medDetailHtml}</div></td><td class="slot time-slot-cell">${slotLabel}</td>${cells}</tr>`,
    );
  }

  function appendMedicationGroupRows(
    rows: string[],
    groups: ReturnType<typeof groupMedicationRows>,
    dayList: number[],
    gapBeforeFirstGroup: boolean,
  ) {
    let firstGroup = !gapBeforeFirstGroup;
    for (const slots of groups) {
      if (!firstGroup) {
        rows.push(`<tr class="gap"><td colspan="${2 + dayList.length}"></td></tr>`);
      }
      firstGroup = false;
      const head = slots[0]!;
      const medDetailHtml = buildMedicationDetailHtml(head);
      slots.forEach((row, slotIndex) => {
        const medCell =
          slotIndex === 0
            ? `<td class="med" rowspan="${slots.length}"><div class="med-details">${medDetailHtml}</div></td>`
            : '';
        const window =
          row.roundWindowStart && row.roundWindowEnd
            ? `${row.roundWindowStart}–${row.roundWindowEnd}`
            : '';
        const slotLabel = row.dueTime
          ? `${escapeHtml(row.timeSlot)}<div class="slot-time">${escapeHtml(row.dueTime)}${window ? ` · ${escapeHtml(window)}` : ''}</div>`
          : escapeHtml(row.timeSlot);
        const cells = dayList
          .map(d => {
            const cell = row.days.find(c => c.day === d);
            if (!cell) return '<td class="status-cell day-cell na"></td>';
            const label = cellLabel(cell);
            return `<td class="status-cell day-cell"${cellStyle(cell)}>${escapeHtml(label)}</td>`;
          })
          .join('');
        rows.push(`<tr>${medCell}<td class="slot">${slotLabel}</td>${cells}</tr>`);
      });
    }
  }

  const orgLine = ctx.organisationName
    ? `<p class="org">${escapeHtml(ctx.organisationName)}</p>`
    : '';

  const excelExtraCss = forExcel
    ? `
    table.mar-grid { min-width: ${160 + 80 + days.length * 32}px; }
    td.day-cell, th.day-col { width: 32px; min-width: 32px; max-width: 36px; }
    td.status-cell { mso-number-format: "\\@"; }
    @page { margin: 0.5in; }`
    : '';

  const excelXml = forExcel
    ? `<?xml version="1.0"?>
<?mso-application progid="Excel.Sheet"?>
`
    : '';

  return `${excelXml}<!DOCTYPE html>
<html xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:x="urn:schemas-microsoft-com:office:excel" lang="en">
<head>
  <meta charset="utf-8" />
  <title>MAR ${escapeHtml(chart.month)} — ${escapeHtml(ctx.serviceUserLabel)}</title>
  ${forExcel ? '<!--[if gte mso 9]><xml><x:ExcelWorkbook><x:ExcelWorksheets><x:ExcelWorksheet><x:Name>MAR</x:Name><x:WorksheetOptions><x:Print><x:ValidPrinterInfo/></x:Print></x:WorksheetOptions></x:ExcelWorksheet></x:ExcelWorksheets></x:ExcelWorkbook></xml><![endif]-->' : ''}
  <style>
    body { font-family: Arial, Helvetica, sans-serif; font-size: 10px; margin: 16px; color: #1e293b; }
    .org { text-align: center; font-size: 11px; font-weight: 600; color: #475569; margin: 0 0 4px; }
    h1 { font-size: 16px; text-align: center; margin: 0 0 4px; letter-spacing: 0.08em; }
    .sub { text-align: center; color: #64748b; margin-bottom: 12px; font-size: 12px; }
    .meta { display: grid; grid-template-columns: 1fr 1fr; gap: 6px 20px; font-size: 10px; margin-bottom: 12px; border: 2px solid #1e293b; padding: 12px; border-radius: 4px; }
    .meta-label { color: #64748b; }
    .legend-block { margin-bottom: 10px; }
    .legend-title { font-size: 10px; font-weight: 700; text-transform: uppercase; letter-spacing: 0.05em; margin-bottom: 4px; color: #475569; }
    table.mar-grid { border-collapse: collapse; width: 100%; table-layout: fixed; }
    th, td { border: 1px solid #cbd5e1; padding: 3px 4px; text-align: center; vertical-align: top; }
    th { background: #f1f5f9; font-weight: 700; }
    th .dow { font-size: 8px; font-weight: 400; color: #64748b; }
    td.med { text-align: left; }
    td.med .med-details { font-size: 9px; line-height: 1.35; }
    td.med .med-detail-label { color: #64748b; font-weight: 600; }
    td.med .med-detail-value { color: #0f172a; font-weight: 700; }
    td.slot { font-weight: 600; text-align: center; }
    td.slot .slot-time { font-size: 8px; color: #64748b; font-weight: 400; }
    tr.gap td { border: none; height: 6px; background: #f8fafc; padding: 0; }
    tr.pack-header-row td { background: #f5f3ff; color: #6d28d9; font-weight: 700; text-align: left; padding: 6px 8px; border: 1px solid #e9d5ff; }
    tr.bp-compartment-summary-row td { border-top: 2px solid #e9d5ff; vertical-align: middle; }
    tr.bp-compartment-summary-row td.bp-comp-summary-sticky-band { padding: 0; border-left: 3px solid #8b5cf6; background: #faf5ff !important; }
    tr.bp-compartment-summary-row .bp-comp-summary-band { display: flex; align-items: stretch; width: 100%; min-height: 44px; }
    tr.bp-compartment-summary-row .bp-comp-summary-label { flex: 1; min-width: 0; padding: 8px 10px; text-align: left; }
    tr.bp-compartment-summary-row .bp-comp-summary-time-side { flex-shrink: 0; width: 72px; box-sizing: border-box; padding: 8px 10px; background: #f5f3ff; border-left: 1px solid #e9d5ff; text-align: center; }
    tr.bp-compartment-summary-row .med-name { font-weight: 600; color: #6d28d9; font-size: 10px; line-height: 1.3; }
    tr.bp-compartment-summary-row .med-meta { font-size: 9px; color: #64748b; margin-top: 3px; line-height: 1.35; }
    tr.bp-compartment-summary-row .med-label-head { display: flex; align-items: center; gap: 6px; flex-wrap: wrap; }
    tr.bp-compartment-summary-row .time-slot-label { font-weight: 600; font-size: 9px; color: #6d28d9; line-height: 1.25; }
    tr.bp-compartment-summary-row .time-slot-time { font-size: 8px; color: #64748b; margin-top: 2px; }
    .bp-comp-status-pill { font-size: 8px; font-weight: 700; text-transform: uppercase; letter-spacing: 0.04em; padding: 2px 6px; border-radius: 999px; white-space: nowrap; }
    .bp-comp-status-pill.open { background: #dbeafe; color: #1d4ed8; border: 1px solid #bfdbfe; }
    .bp-comp-status-pill.complete { background: #dcfce7; color: #15803d; border: 1px solid #bbf7d0; }
    .bp-comp-status-pill.partial { background: #ffedd5; color: #c2410c; border: 1px solid #fed7aa; }
    .bp-comp-status-pill.mixed-due { background: #fef9c3; color: #854d0e; border: 1px solid #fde68a; }
    tr.pack-member-row td { background: #fefefe; }
    tr.pack-member-row td.med { border-left: 3px solid #ddd6fe; }
    td.status-cell.day-cell { font-weight: 700; text-align: center; vertical-align: middle; }
    tr.bp-compartment-summary-row td.comp-day-summary-cell { font-weight: 700; text-align: center; vertical-align: middle; }
    .legend { display: flex; flex-wrap: wrap; gap: 6px; font-size: 9px; }
    .legend-item { padding: 2px 6px; border-radius: 2px; font-weight: 700; }
    @media print { body { margin: 8px; } }${excelExtraCss}
  </style>
</head>
<body class="mar-cal-root">
  ${orgLine}
  <h1>MEDICATION ADMINISTRATION RECORD</h1>
  <p class="sub">${escapeHtml(ctx.reportMonthLabel)}</p>
  <div class="meta">${buildMetaGrid(ctx)}</div>
  ${legendHtml}
  <table class="mar-grid">
    ${buildColgroup(days.length, forExcel)}
    <thead><tr><th>Medication</th><th>Time slot</th>${headerCells}</tr></thead>
    <tbody>${bodyRows.join('')}</tbody>
  </table>
</body>
</html>`;
}
