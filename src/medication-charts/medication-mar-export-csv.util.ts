import type { MarExportChartPayload, MarExportContext } from './medication-mar-export-shared.util';
import { marCompletionMetaRows } from './medication-mar-completion.util';
import {
  cellExportCode,
  cellExportLabel,
  csvRow,
  dayColumnHeader,
  dayOfWeekShort,
  formatUkDateTime,
  groupMedicationRows,
  isoDateForDay,
  scheduleTypeLabel,
} from './medication-mar-export-shared.util';

function sectionBanner(title: string): string {
  return csvRow([`=== ${title} ===`]);
}

function metadataSection(ctx: MarExportContext): string[] {
  const rows: [string, string | number | null][] = [
    ['Document type', 'Medication Administration Record (MAR)'],
    ['Organisation', ctx.organisationName ?? ''],
    ['Reporting month', ctx.reportMonthLabel],
    ['Reporting period (ISO)', `${ctx.periodStart} to ${ctx.periodEnd}`],
    ['Service user', ctx.serviceUserLabel],
    ['Preferred name', ctx.preferredName ?? ''],
    ['Date of birth', ctx.dateOfBirth ?? ''],
    ['NHS number', ctx.nhsNumber ?? ''],
    ['Location', ctx.locationName ?? ''],
    ['Service user ID', ctx.serviceUserId],
    ['Known allergies', ctx.allergySummary ?? 'None recorded'],
    ['Medications in report', ctx.medicationCount],
    ['Administration rows', ctx.administrationRowCount],
    ['Generated at', ctx.generatedAt],
    ['Generated by', ctx.generatedBy ?? ''],
  ];
  return [
    sectionBanner('REPORT HEADER'),
    csvRow(['Field', 'Value']),
    ...rows.map(([field, value]) => csvRow([field, value])),
    '',
  ];
}

function monthSummarySection(ctx: MarExportContext): string[] {
  return [
    sectionBanner('MAR COMPLETION (TO DATE)'),
    csvRow(['Metric', 'Value']),
    ...marCompletionMetaRows(ctx.monthStats).map(([label, value]) => csvRow([label, value])),
    '',
  ];
}

function legendSection(
  legend: MarExportChartPayload['legend'],
): string[] {
  if (!legend.length) return [];
  return [
    sectionBanner('STATUS LEGEND'),
    csvRow(['Code', 'Meaning']),
    ...legend.map(item => csvRow([item.code, item.label])),
    '',
  ];
}

const MATRIX_STATIC_HEADERS = [
  'Row #',
  'Medication name',
  'Pack / blister',
  'Schedule pattern',
  'Strength',
  'Dose',
  'Route',
  'Medication type',
  'Frequency',
  'Time slot',
  'Due time (24h)',
  'Administration window',
] as const;

function matrixSection(chart: MarExportChartPayload): string[] {
  const days = Array.from({ length: chart.lastDay }, (_, i) => i + 1);
  const staticCount = MATRIX_STATIC_HEADERS.length;
  const lines: string[] = [
    sectionBanner('DAILY ADMINISTRATION MATRIX'),
    csvRow([
      ...MATRIX_STATIC_HEADERS,
      ...days.map(d => `Day ${d}`),
    ]),
    csvRow([
      ...Array(staticCount).fill(''),
      ...days.map(d => dayOfWeekShort(chart.month, d)),
    ]),
    csvRow([
      ...Array(staticCount).fill(''),
      ...days.map(d => isoDateForDay(chart.month, d)),
    ]),
    csvRow([
      ...MATRIX_STATIC_HEADERS,
      ...days.map(d => dayColumnHeader(chart.month, d)),
    ]),
  ];

  let rowNum = 0;
  const grouped = groupMedicationRows(chart.medications);
  for (const slots of grouped) {
    for (const row of slots) {
      rowNum += 1;
      const window =
        row.roundWindowStart && row.roundWindowEnd
          ? `${row.roundWindowStart}–${row.roundWindowEnd}`
          : '';
      const dayValues = days.map(d => {
        const cell = row.days.find(c => c.day === d);
        return cell ? cellExportCode(cell) : '';
      });
      lines.push(
        csvRow([
          rowNum,
          row.medicationName,
          row.packName ?? '',
          scheduleTypeLabel(row.scheduleType),
          row.strength ?? '',
          row.dose ?? '',
          row.routeName ?? '',
          row.type ?? '',
          row.frequency ?? '',
          row.timeSlot,
          row.dueTime ?? '',
          window,
          ...dayValues,
        ]),
      );
    }
  }
  lines.push('');
  return lines;
}

function longFormatSection(chart: MarExportChartPayload): string[] {
  const lines: string[] = [
    sectionBanner('ADMINISTRATION DETAIL (LONG FORMAT)'),
    csvRow([
      'Date (ISO)',
      'Weekday',
      'Day of month',
      'Medication name',
      'Pack / blister',
      'Schedule pattern',
      'Strength',
      'Dose',
      'Route',
      'Medication type',
      'Frequency',
      'Time slot',
      'Due time (24h)',
      'Cell state',
      'Status code',
      'Status label',
      'Requires manager review',
    ]),
  ];

  for (const row of chart.medications) {
    for (const cell of row.days) {
      lines.push(
        csvRow([
          cell.date,
          dayOfWeekShort(chart.month, cell.day),
          cell.day,
          row.medicationName,
          row.packName ?? '',
          scheduleTypeLabel(row.scheduleType),
          row.strength ?? '',
          row.dose ?? '',
          row.routeName ?? '',
          row.type ?? '',
          row.frequency ?? '',
          row.timeSlot,
          row.dueTime ?? '',
          cell.cellState,
          cellExportCode(cell),
          cellExportLabel(cell),
          cell.requiresReview ? 'Yes' : 'No',
        ]),
      );
    }
  }

  lines.push('');
  lines.push(
    csvRow([
      'Notes',
      'Matrix uses short status codes; long format includes full labels. N/A = not scheduled on that day.',
    ]),
  );
  lines.push(
    csvRow([
      'Exported at',
      formatUkDateTime(),
    ]),
  );

  return lines;
}

export function buildMarExportCsv(
  ctx: MarExportContext,
  chart: MarExportChartPayload,
  _options?: import('./medication-mar-export-shared.util').MarExportRenderOptions,
): string {
  const lines: string[] = [
    csvRow(['CareFlow — Medication Administration Record Export']),
    '',
    ...metadataSection(ctx),
    ...monthSummarySection(ctx),
    ...legendSection(chart.legend),
    ...matrixSection(chart),
    ...longFormatSection(chart),
  ];

  return `\uFEFF${lines.join('\r\n')}\r\n`;
}
