function slugCode(name) {
  return name
    .trim()
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, '_')
    .replace(/^_|_$/g, '')
    .slice(0, 48);
}

function buildCategoryEntries(category, names) {
  const seen = new Set();
  const out = [];
  for (const name of names) {
    const trimmed = name.trim();
    if (!trimmed) continue;
    const base = `${category}_${slugCode(trimmed)}`;
    let code = base;
    let n = 2;
    while (seen.has(code)) {
      code = `${base}_${n++}`;
    }
    seen.add(code);
    out.push({ name: trimmed, code, category });
  }
  return out;
}

