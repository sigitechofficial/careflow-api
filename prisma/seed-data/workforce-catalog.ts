import { ComplianceCategory } from '@prisma/client';
import type { CareComplianceTypeDef } from './care-compliance-catalog';

export type WorkforceComplianceDef = CareComplianceTypeDef;

export type WorkforceRequirementDef = {
  complianceCode: string;
  roleName?: string;
  workAreaName?: string;
  jobTitleName?: string;
  contractTypeName?: string;
  isMandatory?: boolean;
  renewalBeforeDays?: number;
};

export type WorkforceReviewTypeDef = {
  name: string;
  code: string;
  /** REPEATING: days between reviews. EVENT: follow-up gap once one is recorded. */
  defaultIntervalDays: number | null;
  description?: string;
  /** Defaults to REPEATING (see employee-review-schedule.util.ts). */
  scheduleKind?: 'REPEATING' | 'MILESTONES' | 'EVENT';
  firstDueAfterStartDays?: number;
  milestoneDays?: number[];
  audience?: 'ALL_STAFF' | 'NMC_REGISTRANTS';
};

function cat(c: keyof typeof ComplianceCategory): ComplianceCategory {
  return ComplianceCategory[c];
}

